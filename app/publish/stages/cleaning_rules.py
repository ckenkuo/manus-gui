"""店小秘发布共用能力：stages.cleaning_rules。各来源流程由 workflows/ 独立定义。"""


def _retry_hint(issues: str, cjk: bool, last_chance: bool = False,
                claim: bool = False, banned: bool = False,
                mark: bool = False) -> str:
    """质检未过后重烧时追加的提示词（⑤b 与 ⑬ 共用）。

    【现在的定位：末发兜底 + 生成失败时的回退，不再是唯一路径】2026-09-22 起，常规
    重烧的加码话术改由 vision.build_retry_hint 看着上一发的产物图逐块生成——因为下面
    这几段是 if/return 互斥的（last_chance / banned / mark / claim / cjk / 乱码兜底，
    2026-09-25 起 mark 成为第五类），而一张图常同时踩好几类，固定模板每发只告知其中
    一类、修完一类又冒另一类（实测 offer 652503071023 的 desc-03「拼音单位 -> perfect
    -> 店铺名」四发各栽在不同地方）。本函数仍保留两处用途，都不可替代：
      - last_chance（末发的「全抹掉」）：日志里唯一真正把图救回来的兜底——实测
        desc-03/desc-04 都是前几发全废、靠它才过；
      - build_retry_hint 失败时（额度/JSON 断尾/产物读不到）的回退。
    下面几段分支话术因此还要继续维护，别当成死代码删掉。

    【为什么必须加码而不是原样重发】原样重发只是赌生图的随机性；把「上一发到底哪里
    没弄好」当成新约束喂回去，命中率明显更高（同 llm._JSON_RETRY_HINT 的取向）。

    每类失败要说不同的话——前两类 2026-08-26 实测出现比例差不多：
      - 残留中文（cjk=True）：要点是「逐块扫，一个字符和标点都不留」；
      - 生图乱码（cjk=False，如 ⑤b main-04 的 `oOaLanTanAt`）：根因是模型硬造英文，
        要点反过来——【认不出就整块删掉，不要编】。对乱码说「请翻译干净」只会让它
        再编一串新的无意义字母。
      - 夸大宣传（claim=True）：这一类【与中文无关】，图上往往一个汉字都没有，说
        「请把中文译干净」模型无处下手、只会原样再出一张。要点是指名那类标语并要求
        【抹除而非翻译】——它与主提示词「商品介绍类文字都翻译保留」正好相反，不点明
        就会被当成该保留的商品信息（正是 images.DEFAULT_TRANSLATE_PROMPT 末尾那条
        要解决的同一件事）。claim 优先于 cjk 判断：一张图两样都有时，「抹掉标语」这句
        不影响译中文，反过来漏了标语就又是一发废图。
    【抽成一个函数】两处给的加码必须一致，各写一份必然漂移。

    【last_chance：最后一发改口径，从「译干净」换成「全抹掉」】2026-09-15 定案。
    前几发一直在要求【翻译并原位替换】，而卡住的那些图恰恰是这件事做不成的图（字太密、
    嵌在花纹里、字号太小）——同一个要求再重复一遍只是换个随机种子，命中率不会变。
    抹除是比翻译【容易得多】的任务：不必读懂、不必排版、不必凑字数，只要把文字层连同
    背景补平。产物是「无文案的干净商品图」，对主图/轮播图完全够用（主图本来不靠文案
    传达信息），也就把「4 发全废、退回带中文的原图」换成了「一张能发的图」。
    故这一发刻意【不再提翻译】：只要提了，模型就会继续尝试译写，白费最后一发。

    【调用方必须对尺码表图豁免】尺码表图抹掉文字就只剩一张空网格，等于废图；⑬ 那边
    走 SIZECHART_TRANSLATE_PROMPT 的那些图不能进这一档（见 _prepare_desc_image）。
    这个判断留在调用方而不是这里：本函数拿不到 rep 的 sizechart 标记，塞进来就得多传
    一个只为一处服务的参数。
    """
    head = f"【上一次处理后仍不合格：{issues[:40]}】"
    if last_chance:
        return head + ("前几次尝试把文字翻译成英文都没有成功，这一次改变做法："
                       "不要再翻译、不要生成任何新的文字。请把图片上所有叠加的文案层"
                       "（中文、英文、水印、店铺名、角标、说明文字）全部抹除干净，"
                       "抹除处按周围画面自然补全，最终图上不留任何后期添加的文字。"
                       "商品实物上的装饰性印花、刺绣、图案要原样保留，"
                       # 【末发也要点名实物上的这两类】它们的代价最实（侵权与材质不符），
                       # 而「抹掉所有叠加文案层」这句话管不到实物上的标；不点明的话，
                       # 一张只有实物红标的图在这一发之后仍会带着标过质检。
                       "但实物上的品牌标识（商标、品牌名、品牌小标签）与材质成分说明"
                       "（「棉」「100% Cotton」这类）要一并抹掉——前者构成商标侵权，"
                       "后者会与平台属性里填的材质对不上。"
                       "商品主体、配色、图案和构图完全不变。")
    # 【banned 排在 claim 之前】两样都有时先说禁词：禁词是「整句连同它说明的信息一起
    # 抹掉」，比 claim 那句「抹标语、留客观介绍」更严，先说不会漏掉 claim 要做的事，
    # 反过来则会让模型以为「客观介绍照旧保留」而把「PP棉填充」这类当介绍留下来
    # （同 claim 优先于 cjk 的理由）。
    # 【mark 排在 claim 之前、banned 之后】它判的是【实物上的】品牌标识与材质说明
    # （2026-09-25 新增，见 claims.MARK_REMOVE_RULE）：与 claim 相比它是侵权与材质不符
    # 这类实罚，且 claim 那句「客观介绍照旧翻译保留」会把材质说明当介绍留下来——同
    # 上面 banned 优先于 claim 的理由。
    # 【为什么仍排在 banned 之后】两类的严度现在相同（PP棉 2026-09-25 也改成整段抹掉，
    # 不再是「改名保留」），顺序只决定「同时踩两类时先说哪一句」，先说禁词不会漏掉实物
    # 标记那件事——反过来也一样。若以后要调这个顺序，按「哪类的漏检代价更大」来定，
    # 别再引用已经消失的「PP棉要改名」这条理由。
    if banned:
        return head + ("图上仍有平台禁词，分两种处置："
                       "①「安抚」类用途描述（安抚、安抚玩偶、Soothing、Soother、"
                       "Comforter）【不要翻译、不要保留】，连同所在整句文案与它的底色块"
                       "一起抹除干净、按周围画面自然补全；"
                       # ② 2026-09-25 由「改名保留」改为「抹掉」：改名产物仍是材质声明，
                       # 会撞上实物标记那条（质检必判 materialText），两条要求打架时
                       # 模型怎么改都过不了。理由详见 claims.BANNED_REMOVE_RULE 那段。
                       "②「PP棉」类填充物俗称（PP棉、pp棉、聚丙烯棉、PP Cotton）"
                       "【不要照译、也不要改写成 Polyester Fiber 这类规范材质名】，"
                       "连同所在整句一起抹掉——图上任何材质成分说明都不再保留。"
                       "Comfort（舒适）不是禁词，可以不动。"
                       # 【这一句必须带上括号里的例外】分支是 if/return 互斥的，同时踩禁词
                       # 与实物标记（如 eco 角标 + 口袋方标）时只会走到这里；只说「实物上的
                       # 装饰性印花刺绣保留」等于反向暗示实物上的标也别动，那一发就白烧。
                       "商品实物上的装饰性印花、刺绣、图案原样保留"
                       "（实物上的品牌标识与材质成分说明不在此列，仍要抹掉）；"
                       "尺寸、件数这类不含上述词的客观介绍照旧翻译保留。"
                       # 环保声明是 2026-09-25 并进禁词表的一类，处置与「安抚」相同：
                       # 整句删掉、不许换一种环保说法保留。提示词里必须点出来，否则模型
                       # 只知道「禁词」是哪几个、会把 eco-friendly 当成该保留的介绍类文字。
                       "图上若有环保声明（eco-friendly、environmental friendly、"
                       "sustainable、环保、可持续、可降解这类），【不要翻译、不要保留、"
                       "也不要用别的环保说法替换】，连同所在整句文案一起抹除干净——"
                       "任何环保声明平台都不接受。")
    if mark:
        # 实物上的两类（品牌标识 / 材质成分说明）2026-09-25 用户定案后加的加码话术。
        # 它们与 claim/banned 的区别是【判的是实物】：实物原先一律豁免，说「清除文案层」
        # 模型就不会去动那条缝在口袋上的小标，不点名这一发等于白烧。
        return head + ("图上的品牌标识与材质成分说明还没处理干净，两类处置："
                       "① 品牌标识（商标、品牌名、商品实物上的品牌小标签——牛仔裤后腰的"
                       "红标、鞋侧标、口袋上的方标这类）【不要翻译、不要保留】，连同标签与"
                       "它的底色块一起抹除干净、按周围画面自然补全，它们会构成商标侵权；"
                       "② 材质成分说明（「棉」「纯棉」「100% Cotton」「聚酯纤维」这类，"
                       "无论印在实物标签、吊牌、织标上还是叠加的文案层上）同样抹掉"
                       "——图上材质会与平台属性里填的材质对不上。"
                       "商品实物上的装饰性印花、刺绣、图案照旧保留；"
                       "尺寸、件数、使用说明这类客观介绍照旧翻译保留。")
    if claim:
        return head + ("图上仍有夸大宣传或绝对化宣称的文案（BEST-SELLER、Best Seller、"
                       "Hot Sale、Top Quality、Premium、Must Have、Amazing、Guaranteed、"
                       "热卖、爆款、销量第一、最好、完美、顶级、必备、神器这类）。"
                       "这些标语【不要翻译、不要改写、不要保留】，连同它们的底色块、"
                       "边框和角标一起抹除干净，抹除处按周围画面自然补全。"
                       "请特别检查四角、顶部横幅和边缘的角标——纯英文的标语同样要清掉。"
                       "商品实物上的装饰性印花、刺绣、图案原样保留"
                       "（实物上的品牌标识与材质成分说明不在此列，仍要抹掉）；"
                       "尺寸、件数、使用说明这类客观介绍文字照旧翻译保留。")
    if cjk:
        return head + ("请逐块检查图上每一处文字，包括竖排文字、角标、小字号说明、"
                       "以及印在色块或图案上的文字，一个中文字符和中文标点都不能留下。")
    return head + ("上一次生成的英文是无意义的拼写。请不要凭猜测编造英文单词："
                   "看不清或认不出的文字直接连同背景一起干净移除，"
                   "只保留你能确读并正确翻译的内容。")
